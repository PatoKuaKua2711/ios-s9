#!/usr/bin/env python3
# Embed the Adreno 630 GMU firmware (a630_gmu.bin) into a C header the shim
# stage m10 includes. The firmware is Qualcomm proprietary and NEVER committed:
# this writes shim/fw_a630_gmu.h, which is git-ignored.
#
# The GMU loads its firmware as a raw image into ITCM through AHB registers, one
# 32-bit word at a time (drivers/gpu/msm/adreno_a6xx.c a6xx_gmu_fw_start,
# TCM_BOOT; MAX_GMUFW_SIZE = 0x2000 words). The linux-firmware a630_gmu.bin is
# exactly 32768 bytes = 8192 words.
#
#   tools/gpu-fw-embed.py research/gpu-fw/a630_gmu.bin
#
# Get a630_gmu.bin from linux-firmware (qcom/a630_gmu.bin, redistributable under
# LICENSE.qcom) or from the phone's Android /vendor/firmware. Put it in
# research/gpu-fw/ (git-ignored) first.
import sys
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "shim", "fw_a630_gmu.h")


def main():
    if len(sys.argv) != 2:
        print("usage: gpu-fw-embed.py path/to/a630_gmu.bin", file=sys.stderr)
        return 2
    data = open(sys.argv[1], "rb").read()
    if len(data) % 4:
        print("not a whole number of 32-bit words: %d bytes" % len(data), file=sys.stderr)
        return 2
    if not (0x4000 <= len(data) <= 0x8000):
        print("unexpected size %d (a630_gmu.bin is ~32768 bytes)" % len(data), file=sys.stderr)
        return 2
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    with open(OUT, "w") as f:
        f.write("/* GENERATED by tools/gpu-fw-embed.py from a630_gmu.bin (Qualcomm; NOT in git). */\n")
        f.write("#define HAVE_GMU_FW 1\n")
        f.write("static const uint32_t a630_gmu_fw[%d] = {\n" % len(words))
        for i in range(0, len(words), 8):
            f.write("\t" + " ".join("0x%08xu," % w for w in words[i:i + 8]) + "\n")
        f.write("};\n")
    print("wrote %s (%d words)" % (OUT, len(words)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
